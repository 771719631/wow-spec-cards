function asset(path: string): string {
  const base = import.meta.env.BASE_URL
  return encodeURI(`${base}${path.replace(/^\//, '')}`)
}

export function allSfxRel(): string[] {
  return [...new Set([...Object.values(SKILL_SOUNDS), ...Object.values(CLASS_SOUNDS)])].sort()
}

export function skillSoundRel(specId: string, skillId: string, classId: string): string | null {
  return SKILL_SOUNDS[`${specId}:${skillId}`] ?? CLASS_SOUNDS[classId] ?? null
}

export function skillSoundUrl(specId: string, skillId: string, classId: string): string | null {
  const override = skillPatch(specId, skillId as SkillId)?.sound
  const rel = override || skillSoundRel(specId, skillId, classId)
  return rel ? asset(rel) : null
}
